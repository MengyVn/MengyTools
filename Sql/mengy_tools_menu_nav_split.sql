-- =====================================================================
-- MengyTools - 增量迁移：将"导航站点/导航分类"从「博客管理」下分离，
--                  归入新建的一级菜单「导航管理」。
-- 前置：已执行 mengy_tools_menu_refactor.sql（DB 中存在 140-154 菜单）。
-- 执行：mysql -uroot -p mengy_tools < mengy_tools_menu_nav_split.sql
-- 影响：
--   - 删除原 140-154 共 15 条菜单（导航站点/导航分类及其按钮）与对应 sys_role_menu
--   - 新增 300 一级菜单「导航管理」+ 310-314 导航站点 + 320-324 导航分类
--   - admin 角色重新授权这些新菜单（editor 不受影响，仍仅 article:*）
--   - 「系统服务」排序从 2 调整为 3（让位给排第二的「导航管理」）
--   - 不动 sys_user / sys_role / sys_user_role
-- =====================================================================
USE `mengy_tools`;
SET NAMES utf8mb4;

-- -------------------------------------------------------------------
-- 1. 删除原"导航站点/导航分类"相关授权
-- -------------------------------------------------------------------
DELETE FROM `sys_role_menu` WHERE `menu_id` BETWEEN 140 AND 154;

-- -------------------------------------------------------------------
-- 2. 删除原"导航站点/导航分类"菜单记录（含按钮）
-- -------------------------------------------------------------------
DELETE FROM `sys_menu` WHERE `id` BETWEEN 140 AND 154;

-- -------------------------------------------------------------------
-- 3. 新增「导航管理」一级菜单及其子菜单
--    字段顺序: id, parent_id, menu_name, menu_type, permission, path, component, icon, sort, visible, status, deleted
-- -------------------------------------------------------------------
INSERT INTO `sys_menu`
  (`id`, `parent_id`, `menu_name`, `menu_type`, `permission`, `path`, `component`, `icon`, `sort`, `visible`, `status`, `deleted`) VALUES
-- === 一级：导航管理（sort=2，位于 博客管理(1) 与 系统服务(3) 之间） ===
(300, 0,   '导航管理', 'M', '',                'nav',               '',                     'Location',     2, 1, 1, 0),

-- --- 导航站点 ---
(310, 300, '导航站点', 'C', '',                'nav/site',          'nav/site-list',        'Link',         1, 1, 1, 0),
(311, 310, '站点列表', 'F', 'nav:list',   '', '', '', 1, 1, 1, 0),
(312, 310, '站点新增', 'F', 'nav:add',    '', '', '', 2, 1, 1, 0),
(313, 310, '站点编辑', 'F', 'nav:edit',   '', '', '', 3, 1, 1, 0),
(314, 310, '站点删除', 'F', 'nav:delete', '', '', '', 4, 1, 1, 0),

-- --- 导航分类 ---
(320, 300, '导航分类', 'C', '',                'nav/category',      'nav/category-list',    'FolderOpened', 2, 1, 1, 0),
(321, 320, '分类列表', 'F', 'nav:category:list',   '', '', '', 1, 1, 1, 0),
(322, 320, '分类新增', 'F', 'nav:category:add',    '', '', '', 2, 1, 1, 0),
(323, 320, '分类编辑', 'F', 'nav:category:edit',   '', '', '', 3, 1, 1, 0),
(324, 320, '分类删除', 'F', 'nav:category:delete', '', '', '', 4, 1, 1, 0);

-- -------------------------------------------------------------------
-- 4. admin 角色授权新菜单
--    editor 仍仅 article:*，不涉及 nav:*，故无需改动
-- -------------------------------------------------------------------
INSERT INTO `sys_role_menu` (`role_id`, `menu_id`)
SELECT 1, `id` FROM `sys_menu` WHERE `id` BETWEEN 300 AND 324;

-- -------------------------------------------------------------------
-- 5. 调整「系统服务」排序，让侧边栏顺序为 博客管理(1) → 导航管理(2) → 系统服务(3)
-- -------------------------------------------------------------------
UPDATE `sys_menu` SET `sort` = 3 WHERE `id` = 200;

